#!/usr/bin/env python3
"""Generate source membership documentation from pinned public FIX XML."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
APPLICATIONS = (
    ("FIX.4.0", "FIX40.xml"),
    ("FIX.4.1", "FIX41.xml"),
    ("FIX.4.2", "FIX42.xml"),
    ("FIX.4.3", "FIX43.xml"),
    ("FIX.4.4", "FIX44.xml"),
    ("FIX.5.0", "FIX50.xml"),
    ("FIX.5.0SP1", "FIX50SP1.xml"),
    ("FIX.5.0SP2", "FIX50SP2.xml"),
)
TRANSPORT = ("FIXT.1.1", "FIXT11.xml")


@dataclass(frozen=True)
class Field:
    name: str
    values: dict[str, str]


@dataclass(frozen=True)
class Source:
    version: str
    filename: str
    fields: dict[int, Field]
    messages: dict[str, str]


def load_source(directory: Path, version: str, filename: str) -> Source:
    root = ET.parse(directory / filename).getroot()
    fields = {
        int(field.attrib["number"]): Field(
            field.attrib["name"],
            {value.attrib["enum"]: value.get("description", "")
             for value in field.findall("value")},
        )
        for field in root.findall("./fields/field")
    }
    messages = {message.attrib["msgtype"]: message.attrib["name"]
                for message in root.findall("./messages/message")}
    return Source(version, filename, fields, messages)


def load_sources(directory: Path) -> tuple[list[Source], Source]:
    applications = [load_source(directory, version, filename)
                    for version, filename in APPLICATIONS]
    transport = load_source(directory, *TRANSPORT)
    return applications, transport


def values_absent_from_latest(
    sources: list[Source], metadata: ET.Element,
) -> list[tuple[int, str, dict[str, list[str]]]]:
    """An enum's identity is its tag and value, even when labels change."""
    latest = {int(field.attrib["id"]): {code.attrib["value"]
              for code in field.findall("code")}
              for field in metadata.findall("./fields/field")}
    missing: dict[tuple[int, str], dict[str, list[str]]] = {}
    for source in sources:
        for tag, field in source.fields.items():
            for value, description in field.values.items():
                if value not in latest.get(tag, set()):
                    labels = missing.setdefault((tag, value), {})
                    labels.setdefault(description, []).append(source.version)
    return [(tag, value, labels)
            for (tag, value), labels in sorted(missing.items())]


def markdown(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(directory: Path) -> str:
    applications, transport = load_sources(directory)
    metadata = ET.parse(directory / "FIXLatest-metadata.xml").getroot()
    latest_fields = {int(field.attrib["id"]): field
                     for field in metadata.findall("./fields/field")}
    sources = [*applications, transport]
    application_tags = set().union(*(source.fields for source in applications))
    known_tags = application_tags | transport.fields.keys()
    names = {tag: field.name for source in sources
             for tag, field in source.fields.items()}
    rows = [
        "<!-- Generated by tools/tag_inventory.py; do not edit. -->",
        "# Public FIX dictionary field membership", "",
        "Sources and hashes: [xml/README.md](../xml/README.md). "
        "These tables read the original pinned QuickFIX/J XML and FIX Orchestra "
        "metadata independently of the Rust generator.", "",
        "FIXT.1.1 is a standalone transport source. The eight application "
        "columns are chronological; the transport column is separate. "
        "Absence from a FIX5 application file does not mean a transport field "
        "was removed. No session composition or state is represented here.", "",
        "Counts below are raw source membership. Rust adds presentation metadata "
        "and eligible historical enum values from Orchestra; it never adds "
        "transport fields or messages to application sources.", "",
        "| Source | File | Fields | Raw enum values | Messages |",
        "|---|---|---:|---:|---:|",
    ]
    for source in sources:
        rows.append(f"| {source.version} | `{source.filename}` | "
                    f"{len(source.fields)} | "
                    f"{sum(len(field.values) for field in source.fields.values())} | "
                    f"{len(source.messages)} |")
    rows.extend(["", f"Application field union: **{len(application_tags)}**. "
                 f"Including independent transport: **{len(known_tags)}**. "
                 f"FIX Latest-only fields: **{len(latest_fields.keys() - known_tags)}**.", "",
                 "## Removing the former SP2 transport merge", ""])
    sp2 = applications[-1]
    extra_tags = sorted(transport.fields.keys() - sp2.fields.keys())
    extra_values = sum(len(field.values.keys() - sp2.fields[tag].values.keys())
                       if tag in sp2.fields else len(field.values)
                       for tag, field in transport.fields.items())
    rows.extend([
        f"The former merge added **{len(extra_tags)} fields**, "
        f"**{extra_values} enum values**, and "
        f"**{len(transport.messages.keys() - sp2.messages.keys())} administrative messages** "
        "to SP2. These remain in FIXT11.xml alone; they are not SP2 application definitions.", "",
        ", ".join(f"{names[tag]}({tag})" for tag in extra_tags) + ".", "",
        "Only four of these fields occur in no application source: " + ", ".join(
            f"{names[tag]}({tag})"
            for tag in sorted(transport.fields.keys() - application_tags)) + ".", "",
        "## Field membership", "",
        "A check mark means the original source declares the field. "
        "Names use the newest application source defining the field, "
        "or standalone FIXT for a transport-only field.", "",
        "| Field | " + " | ".join(source.version for source in sources) + " | FIX Latest |",
        "|---|" + "---|" * (len(sources) + 1),
    ])
    for tag in sorted(known_tags):
        # Transport supplies names only for fields absent from every application.
        name = next((source.fields[tag].name for source in reversed(applications)
                     if tag in source.fields), names[tag])
        row = [markdown(f"{name}({tag})")]
        row.extend("✓" if tag in source.fields else "" for source in sources)
        row.append("✓" if tag in latest_fields else "")
        rows.append("| " + " | ".join(row) + " |")
    rows.extend(["", "## Enum values absent from FIX Latest", "",
                 "Identity is the field and value; changing labels share one row. "
                 "Membership comes from original XML, before metadata enrichment.", "",
                 "| Field and value | Source descriptions and membership |",
                 "|---|---|"])
    for tag, value, labels in values_absent_from_latest(sources, metadata):
        descriptions = "; ".join(
            f"{description} ({', '.join(versions)})"
            for description, versions in sorted(labels.items()))
        rows.append(f"| {markdown(names[tag])}({tag}) = {markdown(value)} | "
                    f"{markdown(descriptions)} |")
    return "\n".join(rows) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--xml-dir", type=Path, default=ROOT / "xml/standard")
    parser.add_argument("--output", type=Path, default=ROOT / "docs/tags.md")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    generated = render(arguments.xml_dir)
    if arguments.check:
        if (not arguments.output.exists()
                or arguments.output.read_text(encoding="utf-8") != generated):
            parser.exit(1, f"{arguments.output} differs; regenerate with tools/tag_inventory.py\n")
    else:
        arguments.output.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
